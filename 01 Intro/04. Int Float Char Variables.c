#include <stdio.h>

int main() {
    int i = 5;
    float f = 3.141593;
    char c = 'a';

    i = 5;
    f = 3.141593;
    c = 'a';


    printf("The integer value: %d\n", i);
    printf("The floating point value: %f\n", f);
    printf("The character value: %c\n", c);

    i = 100;
    f = 1.618;
    c = 'z';

    printf("The integer value: %d\n", i);
    printf("The floating point value: %f\n", f);
    printf("The character value: %c\n", c);

    return 0;
}
